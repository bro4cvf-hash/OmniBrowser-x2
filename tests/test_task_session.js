const assert = require('node:assert/strict');
const { TaskSession, interrupted, recoveryPrompt } = require('../extensions/chrome/task-session.js');
const { TaskBudget } = require('../extensions/chrome/task-budget.js');
const { PolicyEngine } = require('../extensions/chrome/sidepanel.js');

(async () => {
  const data = {};
  let broken = false;
  const storage = { set: async patch => { if (broken) throw new Error('Storage failed'); Object.assign(data, structuredClone(patch)); } };
  const session = new TaskSession(storage, { id: 'task', prompt: 'Prepare application', journal: [] });
  const id = await session.begin('click', { tabId: 7 });
  assert.equal(data['omniTask:task'].journal[0].status, 'dispatching');
  await session.settle(id, null, new Error('Connection lost after dispatch'));
  assert.equal(session.uncertainWrites.length, 1);
  const restored = interrupted(data['omniTask:task']);
  assert.match(recoveryPrompt(restored), /Do not repeat submissions/);
  assert.equal(restored.status, 'unknown');
  const read = await session.begin('read_page', { tabId: 7 });
  await session.settle(read, { text: 'Application received' });
  assert.equal(session.uncertainWrites.length, 1, 'A page read alone cannot clear an uncertain write');
  await session.acknowledgeReview();
  assert.equal(session.unreviewedWrites.length, 0);
  assert.equal(session.uncertainWrites.length, 1, 'Human review is not a confirmed submission');
  const missing = await session.begin('click', { tabId: 7, selector: 'a[href="#get-started"]' });
  await session.settle(missing, null, Object.assign(new Error('Action timeout: element not found'), { notDispatched: true }));
  assert.equal(session.record.journal.find(item => item.id === missing).status, 'failed');
  assert.equal(session.unreviewedWrites.length, 0, 'A known failure before activation cannot trigger outcome review');
  assert.doesNotMatch(recoveryPrompt(restored, 'full'), /wait for the user to review/);
  assert.match(recoveryPrompt(restored, 'full'), /Inspect their live destinations automatically/);
  const legacy = new TaskSession(storage, { id: 'legacy', journal: [
    { id: 'missing', name: 'click', target: 'a[href="#get-started"]', status: 'unknown', write: true,
      error: 'Action timeout after 5000ms waiting for \'a[href="#get-started"]\': element not found' },
    { id: 'lost', name: 'click', target: '#submit', status: 'unknown', write: true, error: 'Connection lost after dispatch' }
  ] });
  assert.equal(legacy.record.journal[0].status, 'failed', 'Previously saved missing-target errors are repaired');
  assert.equal(legacy.uncertainWrites.length, 1, 'Previously saved transport failures remain uncertain');
  const partial = await session.begin('batch_actions', { tabId: 7 });
  await session.settle(partial, { results: [{ completed: true }, { error: 'Lost response' }] }, new Error('Transport lost'));
  assert.equal(session.record.journal.find(item => item.id === partial).status, 'unknown', 'Partial results cannot resolve a transport exception');
  broken = true;
  await assert.rejects(session.begin('fill', { tabId: 7 }), /Storage failed/);
  await assert.rejects(session.begin('click', { tabId: 7 }), /Storage failed/, 'Checkpoint failure stays closed');

  const usageEvents = [];
  const budget = new TaskBudget({ taskTokenLimit: 1000, inputTokenPrice: 2, outputTokenPrice: 4 }, event => usageEvents.push(event));
  const body = {};
  const ticket = budget.reserve(body, 100);
  assert.equal(body.max_tokens, undefined, 'Legacy task caps do not impose a provider output limit');
  const parallel = budget.reserve({}, 100000);
  assert.equal(parallel.input, 100000, 'Concurrent requests can exceed a legacy task token cap');
  budget.settle(parallel, { data: { usage: { prompt_tokens: 0, completion_tokens: 0 } } });
  budget.settle(ticket, { data: { choices: [], usage: { prompt_tokens: 100, completion_tokens: 200 } } });
  assert.equal(budget.tokens, 300);
  assert.equal(budget.cost, 0.001);
  budget.settle(ticket, null);
  assert.equal(budget.tokens, 300, 'Reservations settle once');
  const lost = budget.reserve({}, 200);
  budget.settle(lost, null);
  assert.equal(budget.tokens, 4596, 'Lost responses still contribute their full estimated usage');
  assert.doesNotThrow(() => budget.check(), 'Usage can exceed the old task token cap');
  assert.equal(usageEvents.at(-1).tokens, 4596);
  const timed = new TaskBudget({ taskMinutes: 1 }); timed.startedAt -= 60001;
  assert.throws(() => timed.check(), /time limit/);
  const resumed = new TaskBudget({ taskTokenLimit: 1000, taskMinutes: 1 }, () => {}, { tokens: 1000000, elapsedMs: 30000 });
  assert.doesNotThrow(() => resumed.check(), 'Recovery ignores legacy caps even after a million tokens');
  const resumedTicket = resumed.reserve({ max_tokens: 8192 }, 118151);
  resumed.settle(resumedTicket, { data: { usage: { prompt_tokens: 118151, completion_tokens: 8192 } } });
  assert.equal(resumed.tokens, 1126343, 'Recovery preserves usage accounting without capping it');
  const cost = new TaskBudget({ taskCostLimit: 0.001, inputTokenPrice: 2, outputTokenPrice: 4 });
  assert.throws(() => cost.reserve({}, 501), /cost limit/);
  const smallCost = new TaskBudget({ taskCostLimit: 0.000201, inputTokenPrice: 2, outputTokenPrice: 4 });
  assert.throws(() => smallCost.reserve({}, 100), /cost limit/, 'Insufficient output allowance is a cost limit');
  const malformed = new TaskBudget({ taskTokenLimit: 1000 });
  const malformedTicket = malformed.reserve({}, 100);
  malformed.settle(malformedTicket, { data: { usage: { prompt_tokens: -1, completion_tokens: -1 }, choices: [] } });
  assert.equal(malformed.tokens, 101, 'Negative provider usage falls back to estimates');
  assert.equal(malformed.estimated, true);
  assert.throws(() => new TaskBudget().reserve({}, NaN), /input token estimate/i);
  const fractional = {};
  new TaskBudget({ taskTokenLimit: 1000 }).reserve(Object.assign(fractional, { max_tokens: 10.9 }), 100);
  assert.equal(fractional.max_tokens, 10, 'Output limits are positive whole tokens');

  const policy = new PolicyEngine({ taskId: 'task' });
  policy.grantFolder('C:/Docs', 'task');
  policy.grantFolder('C:/Other', 'task');
  assert.equal(policy.checkPermission('files_read_many', { paths: ['C:/Docs/a', 'C:/Other/b'] }).allowed, true);
  policy.rules.push({ decision: 'deny', category: 'file_read', path: 'C:/Other' });
  assert.equal(policy.checkPermission('files_read_many', { paths: ['C:/Docs/a', 'C:/Other/b'] }).decision, 'deny');
  policy.grantSite('https://example.com', 'task');
  assert.equal(policy.checkPermission('fill', { url: 'https://example.com:8443/form' }).allowed, false, 'A site grant is scoped to its origin port');
  policy.rules.push({ decision: 'deny', tool: 'click', domain: 'https://example.com' });
  assert.equal(policy.checkPermission('click', { url: 'https://example.com/form' }).decision, 'deny');
  assert.equal(policy.checkPermission('upload_files', { url: 'https://example.com/form', paths: ['C:/Other/file'] }).decision, 'deny', 'Uploads also enforce file-read denials');
  policy.rules.push({ decision: 'allow', tool: 'mcp__search__find', mcpServer: 'search', taskId: 'task' });
  assert.equal(policy.checkPermission('mcp__search__find', {}, { descriptor: { mcpServer: 'search' } }).allowed, true);
  assert.equal(policy.checkPermission('mcp__search__delete', {}, { descriptor: { mcpServer: 'search' } }).allowed, false);
  policy.setTaskId('other');
  assert.equal(policy.checkPermission('mcp__search__find', {}, { descriptor: { mcpServer: 'search' } }).allowed, false);
  console.log('Task journals, interruption recovery, fail-closed storage, shared budgets and dispatch policy passed.');
})().catch(error => { console.error(error); process.exitCode = 1; });
